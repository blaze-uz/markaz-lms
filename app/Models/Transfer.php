<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

class Transfer extends BaseEntity
{
    use SoftDeletes;

    protected $fillable = [
        'number',
        'income_account_id',
        'expense_account_id',
        'amount',
        'created_by',
    ];

    protected static function booting(): void
    {
        parent::booting(); // TODO: Change the autogenerated stub
        self::creating(function ($model) {
            $model->number = self::generateNumber();
        });
    }

    public static function generateNumber(): string
    {
        $maxId = self::max('id');

        return "TRF-" . str_pad(strval($maxId + 1), 7, "0", STR_PAD_LEFT);
    }

    public function incomeAccount(): \Illuminate\Database\Eloquent\Relations\BelongsTo
    {
        return $this->belongsTo(Account::class, 'income_account_id', 'id');
    }

    public function expenseAccount(): \Illuminate\Database\Eloquent\Relations\BelongsTo
    {
        return $this->belongsTo(Account::class, 'expense_account_id', 'id');
    }

    public function transaction(): \Illuminate\Database\Eloquent\Relations\MorphOne
    {
        return $this->morphOne(Transaction::class, 'transactionable');
    }

    public function transferable(): \Illuminate\Database\Eloquent\Relations\MorphTo
    {
        return $this->morphTo();
    }
}
